def normalise(name, art):
    rows = art.split("\n")
    if len(rows) > H:
        sys.exit(f"{name}: {len(rows)} rows, max {H}")
    # Pad at the top only, so every glyph shares a baseline on the cell's last
    # row. Centring instead gave each glyph a baseline of its own - a '4' and a
    # '0' of different heights sat at different depths in the same string - and
    # left the bottom row of the cell empty, so the cell height was not
    # actually load-bearing anywhere.
    rows = ["." * W] * (H - len(rows)) + rows
    out = []
    for i, r in enumerate(rows):
        if len(r) > W:
            sys.exit(f"{name}: row {i} is {len(r)} wide, max {W}")
        out.append(r.ljust(W, "."))
    return out


def preview(glyphs):
    for name, rows in glyphs.items():
        print(f"--- '{name}' ---")
        for r in rows:
            print("  " + r.replace(".", " ").replace("#", "█"))


def emit(glyphs):
    """One byte per column-slice: 16 columns x 3 bytes, LSB = topmost row of
    that slice, matching the 5x7 table's column-major, LSB-at-top layout."""
    print("static const glyph16x24_t FONT_16X24[] = {")
    for name, rows in glyphs.items():
        cols = []
        for x in range(W):
            for byte in range(3):
                v = 0
                for bit in range(8):
                    y = byte * 8 + bit
                    if rows[y][x] == "#":
                        v |= 1 << bit
                cols.append(v)
        body = ", ".join(f"0x{v:02x}" for v in cols)
        esc = "'\\''" if name == "'" else f"'{name}'"
        print(f"    {{ {esc}, {{ {body} }} }},")
    print("};")


def emit_js(glyphs):
    """The same table for webui/epd.js, same packing."""
    print("const FONT16 = {")
    for name, rows in glyphs.items():
        cols = []
        for x in range(W):
            for byte in range(3):
                v = 0
                for bit in range(8):
                    if rows[byte * 8 + bit][x] == "#":
                        v |= 1 << bit
                cols.append(v)
        key = "':'" if name == ":" else f"'{name}'"
        print(f"  {key}: [{', '.join(f'0x{v:02x}' for v in cols)}],")
    print("};")


if __name__ == "__main__":
    g = {k: normalise(k, v) for k, v in ART.items()}
    if "--emit" in sys.argv:
        emit(g)
    elif "--js" in sys.argv:
        emit_js(g)
    else:
        preview(g)
